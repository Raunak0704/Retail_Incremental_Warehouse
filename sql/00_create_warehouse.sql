CREATE DATABASE IF NOT EXISTS RETAIL_DW;
CREATE SCHEMA IF NOT EXISTS RETAIL_DW.RAW;
CREATE SCHEMA IF NOT EXISTS RETAIL_DW.STAGING;
CREATE SCHEMA IF NOT EXISTS RETAIL_DW.DW;
CREATE SCHEMA IF NOT EXISTS RETAIL_DW.CONTROL;
CREATE SCHEMA IF NOT EXISTS RETAIL_DW.AUDIT;

CREATE FILE FORMAT IF NOT EXISTS RETAIL_DW.RAW.RETAIL_PARQUET_FF
  TYPE = PARQUET;

CREATE SEQUENCE IF NOT EXISTS RETAIL_DW.DW.DIM_CUSTOMER_SEQ START = 1 INCREMENT = 1;
CREATE SEQUENCE IF NOT EXISTS RETAIL_DW.DW.DIM_PRODUCT_SEQ START = 1 INCREMENT = 1;

CREATE TABLE IF NOT EXISTS RETAIL_DW.RAW.RAW_CUSTOMERS (
  RECORD VARIANT NOT NULL,
  BATCH_ID VARCHAR(64) NOT NULL,
  SOURCE_FILE VARCHAR(1000),
  LOADED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
);
CREATE TABLE IF NOT EXISTS RETAIL_DW.RAW.RAW_PRODUCTS (
  RECORD VARIANT NOT NULL,
  BATCH_ID VARCHAR(64) NOT NULL,
  SOURCE_FILE VARCHAR(1000),
  LOADED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
);
CREATE TABLE IF NOT EXISTS RETAIL_DW.RAW.RAW_ORDERS (
  RECORD VARIANT NOT NULL,
  BATCH_ID VARCHAR(64) NOT NULL,
  SOURCE_FILE VARCHAR(1000),
  LOADED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
);
CREATE TABLE IF NOT EXISTS RETAIL_DW.RAW.RAW_ORDER_ITEMS (
  RECORD VARIANT NOT NULL,
  BATCH_ID VARCHAR(64) NOT NULL,
  SOURCE_FILE VARCHAR(1000),
  LOADED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS RETAIL_DW.STAGING.STG_CUSTOMERS (
  CUSTOMER_ID NUMBER(38,0), CUSTOMER_NAME VARCHAR(200), EMAIL VARCHAR(320), PHONE VARCHAR(40),
  CITY VARCHAR(100), STATE VARCHAR(100), COUNTRY VARCHAR(100), CUSTOMER_SEGMENT VARCHAR(40),
  IS_DELETED BOOLEAN, CREATED_AT TIMESTAMP_TZ, SOURCE_UPDATED_AT TIMESTAMP_TZ,
  ATTRIBUTE_HASH VARCHAR(64), BATCH_ID VARCHAR(64), SOURCE_FILE VARCHAR(1000)
);
CREATE TABLE IF NOT EXISTS RETAIL_DW.STAGING.STG_PRODUCTS (
  PRODUCT_ID NUMBER(38,0), SKU VARCHAR(80), PRODUCT_NAME VARCHAR(200), CATEGORY VARCHAR(100),
  BRAND VARCHAR(100), UNIT_PRICE NUMBER(14,2), IS_ACTIVE BOOLEAN, IS_DELETED BOOLEAN,
  CREATED_AT TIMESTAMP_TZ, SOURCE_UPDATED_AT TIMESTAMP_TZ,
  ATTRIBUTE_HASH VARCHAR(64), BATCH_ID VARCHAR(64), SOURCE_FILE VARCHAR(1000)
);
CREATE TABLE IF NOT EXISTS RETAIL_DW.STAGING.STG_ORDERS (
  ORDER_ID NUMBER(38,0), CUSTOMER_ID NUMBER(38,0), ORDER_TS TIMESTAMP_TZ,
  ORDER_STATUS VARCHAR(30), PAYMENT_STATUS VARCHAR(30), TOTAL_AMOUNT NUMBER(16,2),
  CURRENCY VARCHAR(3), IS_DELETED BOOLEAN, CREATED_AT TIMESTAMP_TZ,
  SOURCE_UPDATED_AT TIMESTAMP_TZ, BATCH_ID VARCHAR(64), SOURCE_FILE VARCHAR(1000)
);
CREATE TABLE IF NOT EXISTS RETAIL_DW.STAGING.STG_ORDER_ITEMS (
  ORDER_ITEM_ID NUMBER(38,0), ORDER_ID NUMBER(38,0), PRODUCT_ID NUMBER(38,0),
  QUANTITY NUMBER(10,0), UNIT_PRICE NUMBER(14,2), DISCOUNT_AMOUNT NUMBER(14,2),
  LINE_AMOUNT NUMBER(16,2), ITEM_STATUS VARCHAR(30), IS_DELETED BOOLEAN,
  CREATED_AT TIMESTAMP_TZ, SOURCE_UPDATED_AT TIMESTAMP_TZ,
  BATCH_ID VARCHAR(64), SOURCE_FILE VARCHAR(1000)
);

CREATE TABLE IF NOT EXISTS RETAIL_DW.DW.DIM_CUSTOMER (
  CUSTOMER_SK NUMBER(38,0) DEFAULT RETAIL_DW.DW.DIM_CUSTOMER_SEQ.NEXTVAL,
  CUSTOMER_ID NUMBER(38,0) NOT NULL,
  CUSTOMER_NAME VARCHAR(200), EMAIL VARCHAR(320), PHONE VARCHAR(40), CITY VARCHAR(100),
  STATE VARCHAR(100), COUNTRY VARCHAR(100), CUSTOMER_SEGMENT VARCHAR(40),
  IS_DELETED BOOLEAN DEFAULT FALSE,
  ATTRIBUTE_HASH VARCHAR(64) NOT NULL,
  VALID_FROM TIMESTAMP_TZ NOT NULL,
  VALID_TO TIMESTAMP_TZ NOT NULL,
  IS_CURRENT BOOLEAN NOT NULL,
  SOURCE_UPDATED_AT TIMESTAMP_TZ NOT NULL,
  CREATED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS RETAIL_DW.DW.DIM_PRODUCT (
  PRODUCT_SK NUMBER(38,0) DEFAULT RETAIL_DW.DW.DIM_PRODUCT_SEQ.NEXTVAL,
  PRODUCT_ID NUMBER(38,0) NOT NULL,
  SKU VARCHAR(80), PRODUCT_NAME VARCHAR(200), CATEGORY VARCHAR(100), BRAND VARCHAR(100),
  UNIT_PRICE NUMBER(14,2), IS_ACTIVE BOOLEAN, IS_DELETED BOOLEAN DEFAULT FALSE,
  ATTRIBUTE_HASH VARCHAR(64), SOURCE_UPDATED_AT TIMESTAMP_TZ NOT NULL,
  CREATED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP(), UPDATED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS RETAIL_DW.DW.FACT_ORDERS (
  ORDER_ID NUMBER(38,0) NOT NULL,
  CUSTOMER_ID NUMBER(38,0) NOT NULL,
  CUSTOMER_SK NUMBER(38,0),
  ORDER_TS TIMESTAMP_TZ NOT NULL,
  ORDER_STATUS VARCHAR(30), PAYMENT_STATUS VARCHAR(30), TOTAL_AMOUNT NUMBER(16,2),
  CURRENCY VARCHAR(3), IS_DELETED BOOLEAN DEFAULT FALSE,
  SOURCE_UPDATED_AT TIMESTAMP_TZ NOT NULL,
  CREATED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP(), UPDATED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS RETAIL_DW.DW.FACT_ORDER_ITEMS (
  ORDER_ITEM_ID NUMBER(38,0) NOT NULL,
  ORDER_ID NUMBER(38,0) NOT NULL,
  PRODUCT_ID NUMBER(38,0) NOT NULL,
  PRODUCT_SK NUMBER(38,0), CUSTOMER_SK NUMBER(38,0),
  QUANTITY NUMBER(10,0), UNIT_PRICE NUMBER(14,2), DISCOUNT_AMOUNT NUMBER(14,2),
  LINE_AMOUNT NUMBER(16,2), ITEM_STATUS VARCHAR(30), IS_DELETED BOOLEAN DEFAULT FALSE,
  SOURCE_UPDATED_AT TIMESTAMP_TZ NOT NULL,
  CREATED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP(), UPDATED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS RETAIL_DW.CONTROL.ETL_WATERMARK (
  SOURCE_TABLE VARCHAR(100) NOT NULL,
  LAST_SUCCESS_UPDATED_AT TIMESTAMP_TZ,
  LAST_SUCCESS_PRIMARY_KEY NUMBER(38,0),
  LAST_SUCCESS_BATCH_ID VARCHAR(64),
  UPDATED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS RETAIL_DW.AUDIT.ETL_BATCH_LOG (
  BATCH_ID VARCHAR(64) NOT NULL,
  SOURCE_TABLE VARCHAR(100) NOT NULL,
  LOAD_MODE VARCHAR(20) NOT NULL,
  LOWER_WATERMARK TIMESTAMP_TZ,
  UPPER_WATERMARK TIMESTAMP_TZ,
  UPPER_PRIMARY_KEY NUMBER(38,0),
  ROWS_EXTRACTED NUMBER(38,0),
  S3_PREFIX VARCHAR(2000),
  STATUS VARCHAR(30),
  STARTED_AT TIMESTAMP_TZ,
  COMPLETED_AT TIMESTAMP_TZ,
  ERROR_MESSAGE VARCHAR(4000)
);

CREATE TABLE IF NOT EXISTS RETAIL_DW.AUDIT.DATA_QUALITY_RESULTS (
  CHECKED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP(),
  BATCH_ID VARCHAR(64), SOURCE_TABLE VARCHAR(100), CHECK_NAME VARCHAR(200),
  FAILED_ROWS NUMBER(38,0), STATUS VARCHAR(20), DETAILS VARCHAR(4000)
);

CREATE OR REPLACE VIEW RETAIL_DW.DW.VW_CUSTOMER_CURRENT AS
SELECT * FROM RETAIL_DW.DW.DIM_CUSTOMER WHERE IS_CURRENT = TRUE;

CREATE OR REPLACE VIEW RETAIL_DW.DW.VW_DAILY_SALES AS
SELECT TO_DATE(ORDER_TS) AS ORDER_DATE, CURRENCY,
       COUNT(*) AS ORDER_COUNT, SUM(TOTAL_AMOUNT) AS GROSS_ORDER_VALUE
FROM RETAIL_DW.DW.FACT_ORDERS
WHERE IS_DELETED = FALSE AND ORDER_STATUS <> 'CANCELLED'
GROUP BY TO_DATE(ORDER_TS), CURRENCY;
