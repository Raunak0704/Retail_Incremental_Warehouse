DELETE FROM RETAIL_DW.STAGING.STG_ORDERS WHERE BATCH_ID = '{{BATCH_ID}}';

INSERT INTO RETAIL_DW.STAGING.STG_ORDERS (
  ORDER_ID, CUSTOMER_ID, ORDER_TS, ORDER_STATUS, PAYMENT_STATUS, TOTAL_AMOUNT,
  CURRENCY, IS_DELETED, CREATED_AT, SOURCE_UPDATED_AT, BATCH_ID, SOURCE_FILE
)
SELECT ORDER_ID, CUSTOMER_ID, ORDER_TS, ORDER_STATUS, PAYMENT_STATUS, TOTAL_AMOUNT,
       CURRENCY, IS_DELETED, CREATED_AT, SOURCE_UPDATED_AT, BATCH_ID, SOURCE_FILE
FROM (
  SELECT
    RECORD:"ORDER_ID"::NUMBER(38,0) AS ORDER_ID,
    RECORD:"CUSTOMER_ID"::NUMBER(38,0) AS CUSTOMER_ID,
    TRY_TO_TIMESTAMP_TZ(RECORD:"ORDER_TS"::VARCHAR) AS ORDER_TS,
    RECORD:"ORDER_STATUS"::VARCHAR(30) AS ORDER_STATUS,
    RECORD:"PAYMENT_STATUS"::VARCHAR(30) AS PAYMENT_STATUS,
    RECORD:"TOTAL_AMOUNT"::NUMBER(16,2) AS TOTAL_AMOUNT,
    RECORD:"CURRENCY"::VARCHAR(3) AS CURRENCY,
    COALESCE(TRY_TO_BOOLEAN(RECORD:"IS_DELETED"::VARCHAR), FALSE) AS IS_DELETED,
    TRY_TO_TIMESTAMP_TZ(RECORD:"CREATED_AT"::VARCHAR) AS CREATED_AT,
    TRY_TO_TIMESTAMP_TZ(RECORD:"UPDATED_AT"::VARCHAR) AS SOURCE_UPDATED_AT,
    BATCH_ID, SOURCE_FILE,
    ROW_NUMBER() OVER (
      PARTITION BY RECORD:"ORDER_ID"::NUMBER(38,0)
      ORDER BY TRY_TO_TIMESTAMP_TZ(RECORD:"UPDATED_AT"::VARCHAR) DESC, SOURCE_FILE DESC
    ) AS RN
  FROM RETAIL_DW.RAW.RAW_ORDERS
  WHERE BATCH_ID = '{{BATCH_ID}}'
)
WHERE RN = 1;

MERGE INTO RETAIL_DW.DW.FACT_ORDERS T
USING (
  SELECT S.ORDER_ID, S.CUSTOMER_ID, C.CUSTOMER_SK, S.ORDER_TS, S.ORDER_STATUS,
         S.PAYMENT_STATUS, S.TOTAL_AMOUNT, S.CURRENCY, S.IS_DELETED, S.SOURCE_UPDATED_AT
  FROM RETAIL_DW.STAGING.STG_ORDERS S
  LEFT JOIN RETAIL_DW.DW.DIM_CUSTOMER C
    ON C.CUSTOMER_ID = S.CUSTOMER_ID
   AND S.ORDER_TS >= C.VALID_FROM
   AND S.ORDER_TS < C.VALID_TO
  WHERE S.BATCH_ID = '{{BATCH_ID}}'
  QUALIFY ROW_NUMBER() OVER (PARTITION BY S.ORDER_ID ORDER BY C.VALID_FROM DESC) = 1
) S
ON T.ORDER_ID = S.ORDER_ID
WHEN MATCHED AND S.SOURCE_UPDATED_AT > T.SOURCE_UPDATED_AT THEN UPDATE SET
  T.CUSTOMER_ID = S.CUSTOMER_ID,
  T.CUSTOMER_SK = S.CUSTOMER_SK,
  T.ORDER_TS = S.ORDER_TS,
  T.ORDER_STATUS = S.ORDER_STATUS,
  T.PAYMENT_STATUS = S.PAYMENT_STATUS,
  T.TOTAL_AMOUNT = S.TOTAL_AMOUNT,
  T.CURRENCY = S.CURRENCY,
  T.IS_DELETED = S.IS_DELETED,
  T.SOURCE_UPDATED_AT = S.SOURCE_UPDATED_AT,
  T.UPDATED_AT = CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT (
  ORDER_ID, CUSTOMER_ID, CUSTOMER_SK, ORDER_TS, ORDER_STATUS, PAYMENT_STATUS,
  TOTAL_AMOUNT, CURRENCY, IS_DELETED, SOURCE_UPDATED_AT
) VALUES (
  S.ORDER_ID, S.CUSTOMER_ID, S.CUSTOMER_SK, S.ORDER_TS, S.ORDER_STATUS, S.PAYMENT_STATUS,
  S.TOTAL_AMOUNT, S.CURRENCY, S.IS_DELETED, S.SOURCE_UPDATED_AT
);
