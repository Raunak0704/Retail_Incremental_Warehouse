DELETE FROM RETAIL_DW.STAGING.STG_PRODUCTS WHERE BATCH_ID = '{{BATCH_ID}}';

INSERT INTO RETAIL_DW.STAGING.STG_PRODUCTS (
  PRODUCT_ID, SKU, PRODUCT_NAME, CATEGORY, BRAND, UNIT_PRICE, IS_ACTIVE, IS_DELETED,
  CREATED_AT, SOURCE_UPDATED_AT, ATTRIBUTE_HASH, BATCH_ID, SOURCE_FILE
)
SELECT PRODUCT_ID, SKU, PRODUCT_NAME, CATEGORY, BRAND, UNIT_PRICE, IS_ACTIVE, IS_DELETED,
       CREATED_AT, SOURCE_UPDATED_AT,
       SHA2(TO_JSON(ARRAY_CONSTRUCT_KEEP_NULL(
         'sku', SKU, 'product_name', PRODUCT_NAME, 'category', CATEGORY,
         'brand', BRAND, 'unit_price', UNIT_PRICE, 'is_active', IS_ACTIVE,
         'is_deleted', IS_DELETED
       )), 256), BATCH_ID, SOURCE_FILE
FROM (
  SELECT
    RECORD:"PRODUCT_ID"::NUMBER(38,0) AS PRODUCT_ID,
    RECORD:"SKU"::VARCHAR(80) AS SKU,
    RECORD:"PRODUCT_NAME"::VARCHAR(200) AS PRODUCT_NAME,
    RECORD:"CATEGORY"::VARCHAR(100) AS CATEGORY,
    RECORD:"BRAND"::VARCHAR(100) AS BRAND,
    RECORD:"UNIT_PRICE"::NUMBER(14,2) AS UNIT_PRICE,
    COALESCE(TRY_TO_BOOLEAN(RECORD:"IS_ACTIVE"::VARCHAR), TRUE) AS IS_ACTIVE,
    COALESCE(TRY_TO_BOOLEAN(RECORD:"IS_DELETED"::VARCHAR), FALSE) AS IS_DELETED,
    TRY_TO_TIMESTAMP_TZ(RECORD:"CREATED_AT"::VARCHAR) AS CREATED_AT,
    TRY_TO_TIMESTAMP_TZ(RECORD:"UPDATED_AT"::VARCHAR) AS SOURCE_UPDATED_AT,
    BATCH_ID, SOURCE_FILE,
    ROW_NUMBER() OVER (
      PARTITION BY RECORD:"PRODUCT_ID"::NUMBER(38,0)
      ORDER BY TRY_TO_TIMESTAMP_TZ(RECORD:"UPDATED_AT"::VARCHAR) DESC, SOURCE_FILE DESC
    ) AS RN
  FROM RETAIL_DW.RAW.RAW_PRODUCTS
  WHERE BATCH_ID = '{{BATCH_ID}}'
)
WHERE RN = 1;

MERGE INTO RETAIL_DW.DW.DIM_PRODUCT T
USING (
  SELECT * FROM RETAIL_DW.STAGING.STG_PRODUCTS WHERE BATCH_ID = '{{BATCH_ID}}'
) S
ON T.PRODUCT_ID = S.PRODUCT_ID
WHEN MATCHED AND S.SOURCE_UPDATED_AT >= T.SOURCE_UPDATED_AT
  AND S.ATTRIBUTE_HASH <> T.ATTRIBUTE_HASH THEN UPDATE SET
    T.SKU = S.SKU,
    T.PRODUCT_NAME = S.PRODUCT_NAME,
    T.CATEGORY = S.CATEGORY,
    T.BRAND = S.BRAND,
    T.UNIT_PRICE = S.UNIT_PRICE,
    T.IS_ACTIVE = S.IS_ACTIVE,
    T.IS_DELETED = S.IS_DELETED,
    T.ATTRIBUTE_HASH = S.ATTRIBUTE_HASH,
    T.SOURCE_UPDATED_AT = S.SOURCE_UPDATED_AT,
    T.UPDATED_AT = CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT (
  PRODUCT_ID, SKU, PRODUCT_NAME, CATEGORY, BRAND, UNIT_PRICE, IS_ACTIVE, IS_DELETED,
  ATTRIBUTE_HASH, SOURCE_UPDATED_AT
) VALUES (
  S.PRODUCT_ID, S.SKU, S.PRODUCT_NAME, S.CATEGORY, S.BRAND, S.UNIT_PRICE, S.IS_ACTIVE,
  S.IS_DELETED, S.ATTRIBUTE_HASH, S.SOURCE_UPDATED_AT
);
