DELETE FROM RETAIL_DW.STAGING.STG_ORDER_ITEMS WHERE BATCH_ID = '{{BATCH_ID}}';

INSERT INTO RETAIL_DW.STAGING.STG_ORDER_ITEMS (
  ORDER_ITEM_ID, ORDER_ID, PRODUCT_ID, QUANTITY, UNIT_PRICE, DISCOUNT_AMOUNT,
  LINE_AMOUNT, ITEM_STATUS, IS_DELETED, CREATED_AT, SOURCE_UPDATED_AT, BATCH_ID, SOURCE_FILE
)
SELECT ORDER_ITEM_ID, ORDER_ID, PRODUCT_ID, QUANTITY, UNIT_PRICE, DISCOUNT_AMOUNT,
       LINE_AMOUNT, ITEM_STATUS, IS_DELETED, CREATED_AT, SOURCE_UPDATED_AT, BATCH_ID, SOURCE_FILE
FROM (
  SELECT
    RECORD:"ORDER_ITEM_ID"::NUMBER(38,0) AS ORDER_ITEM_ID,
    RECORD:"ORDER_ID"::NUMBER(38,0) AS ORDER_ID,
    RECORD:"PRODUCT_ID"::NUMBER(38,0) AS PRODUCT_ID,
    RECORD:"QUANTITY"::NUMBER(10,0) AS QUANTITY,
    RECORD:"UNIT_PRICE"::NUMBER(14,2) AS UNIT_PRICE,
    RECORD:"DISCOUNT_AMOUNT"::NUMBER(14,2) AS DISCOUNT_AMOUNT,
    RECORD:"LINE_AMOUNT"::NUMBER(16,2) AS LINE_AMOUNT,
    RECORD:"ITEM_STATUS"::VARCHAR(30) AS ITEM_STATUS,
    COALESCE(TRY_TO_BOOLEAN(RECORD:"IS_DELETED"::VARCHAR), FALSE) AS IS_DELETED,
    TRY_TO_TIMESTAMP_TZ(RECORD:"CREATED_AT"::VARCHAR) AS CREATED_AT,
    TRY_TO_TIMESTAMP_TZ(RECORD:"UPDATED_AT"::VARCHAR) AS SOURCE_UPDATED_AT,
    BATCH_ID, SOURCE_FILE,
    ROW_NUMBER() OVER (
      PARTITION BY RECORD:"ORDER_ITEM_ID"::NUMBER(38,0)
      ORDER BY TRY_TO_TIMESTAMP_TZ(RECORD:"UPDATED_AT"::VARCHAR) DESC, SOURCE_FILE DESC
    ) AS RN
  FROM RETAIL_DW.RAW.RAW_ORDER_ITEMS
  WHERE BATCH_ID = '{{BATCH_ID}}'
)
WHERE RN = 1;

MERGE INTO RETAIL_DW.DW.FACT_ORDER_ITEMS T
USING (
  SELECT S.ORDER_ITEM_ID, S.ORDER_ID, S.PRODUCT_ID, P.PRODUCT_SK, O.CUSTOMER_SK,
         S.QUANTITY, S.UNIT_PRICE, S.DISCOUNT_AMOUNT, S.LINE_AMOUNT,
         S.ITEM_STATUS, S.IS_DELETED, S.SOURCE_UPDATED_AT
  FROM RETAIL_DW.STAGING.STG_ORDER_ITEMS S
  LEFT JOIN RETAIL_DW.DW.DIM_PRODUCT P ON P.PRODUCT_ID = S.PRODUCT_ID
  LEFT JOIN RETAIL_DW.DW.FACT_ORDERS O ON O.ORDER_ID = S.ORDER_ID
  WHERE S.BATCH_ID = '{{BATCH_ID}}'
) S
ON T.ORDER_ITEM_ID = S.ORDER_ITEM_ID
WHEN MATCHED AND S.SOURCE_UPDATED_AT > T.SOURCE_UPDATED_AT THEN UPDATE SET
  T.ORDER_ID = S.ORDER_ID,
  T.PRODUCT_ID = S.PRODUCT_ID,
  T.PRODUCT_SK = S.PRODUCT_SK,
  T.CUSTOMER_SK = S.CUSTOMER_SK,
  T.QUANTITY = S.QUANTITY,
  T.UNIT_PRICE = S.UNIT_PRICE,
  T.DISCOUNT_AMOUNT = S.DISCOUNT_AMOUNT,
  T.LINE_AMOUNT = S.LINE_AMOUNT,
  T.ITEM_STATUS = S.ITEM_STATUS,
  T.IS_DELETED = S.IS_DELETED,
  T.SOURCE_UPDATED_AT = S.SOURCE_UPDATED_AT,
  T.UPDATED_AT = CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT (
  ORDER_ITEM_ID, ORDER_ID, PRODUCT_ID, PRODUCT_SK, CUSTOMER_SK, QUANTITY,
  UNIT_PRICE, DISCOUNT_AMOUNT, LINE_AMOUNT, ITEM_STATUS, IS_DELETED, SOURCE_UPDATED_AT
) VALUES (
  S.ORDER_ITEM_ID, S.ORDER_ID, S.PRODUCT_ID, S.PRODUCT_SK, S.CUSTOMER_SK, S.QUANTITY,
  S.UNIT_PRICE, S.DISCOUNT_AMOUNT, S.LINE_AMOUNT, S.ITEM_STATUS, S.IS_DELETED, S.SOURCE_UPDATED_AT
);
