-- Rebuild this batch's typed staging slice. Batch-scoped DELETE makes retries safe.
DELETE FROM RETAIL_DW.STAGING.STG_CUSTOMERS WHERE BATCH_ID = '{{BATCH_ID}}';

INSERT INTO RETAIL_DW.STAGING.STG_CUSTOMERS (
  CUSTOMER_ID, CUSTOMER_NAME, EMAIL, PHONE, CITY, STATE, COUNTRY, CUSTOMER_SEGMENT,
  IS_DELETED, CREATED_AT, SOURCE_UPDATED_AT, ATTRIBUTE_HASH, BATCH_ID, SOURCE_FILE
)
SELECT CUSTOMER_ID, CUSTOMER_NAME, EMAIL, PHONE, CITY, STATE, COUNTRY, CUSTOMER_SEGMENT,
       IS_DELETED, CREATED_AT, SOURCE_UPDATED_AT,
       SHA2(TO_JSON(ARRAY_CONSTRUCT_KEEP_NULL(
         'customer_name', CUSTOMER_NAME, 'email', EMAIL, 'phone', PHONE,
         'city', CITY, 'state', STATE, 'country', COUNTRY,
         'customer_segment', CUSTOMER_SEGMENT, 'is_deleted', IS_DELETED
       )), 256) AS ATTRIBUTE_HASH,
       BATCH_ID, SOURCE_FILE
FROM (
  SELECT
    RECORD:"CUSTOMER_ID"::NUMBER(38,0) AS CUSTOMER_ID,
    RECORD:"CUSTOMER_NAME"::VARCHAR(200) AS CUSTOMER_NAME,
    RECORD:"EMAIL"::VARCHAR(320) AS EMAIL,
    RECORD:"PHONE"::VARCHAR(40) AS PHONE,
    RECORD:"CITY"::VARCHAR(100) AS CITY,
    RECORD:"STATE"::VARCHAR(100) AS STATE,
    RECORD:"COUNTRY"::VARCHAR(100) AS COUNTRY,
    RECORD:"CUSTOMER_SEGMENT"::VARCHAR(40) AS CUSTOMER_SEGMENT,
    COALESCE(TRY_TO_BOOLEAN(RECORD:"IS_DELETED"::VARCHAR), FALSE) AS IS_DELETED,
    TRY_TO_TIMESTAMP_TZ(RECORD:"CREATED_AT"::VARCHAR) AS CREATED_AT,
    TRY_TO_TIMESTAMP_TZ(RECORD:"UPDATED_AT"::VARCHAR) AS SOURCE_UPDATED_AT,
    BATCH_ID, SOURCE_FILE,
    ROW_NUMBER() OVER (
      PARTITION BY RECORD:"CUSTOMER_ID"::NUMBER(38,0)
      ORDER BY TRY_TO_TIMESTAMP_TZ(RECORD:"UPDATED_AT"::VARCHAR) DESC, SOURCE_FILE DESC
    ) AS RN
  FROM RETAIL_DW.RAW.RAW_CUSTOMERS
  WHERE BATCH_ID = '{{BATCH_ID}}'
)
WHERE RN = 1;

-- Expire the currently active version only when tracked attributes changed.
UPDATE RETAIL_DW.DW.DIM_CUSTOMER T
SET VALID_TO = S.SOURCE_UPDATED_AT,
    IS_CURRENT = FALSE
FROM RETAIL_DW.STAGING.STG_CUSTOMERS S
WHERE S.BATCH_ID = '{{BATCH_ID}}'
  AND T.CUSTOMER_ID = S.CUSTOMER_ID
  AND T.IS_CURRENT = TRUE
  AND T.ATTRIBUTE_HASH <> S.ATTRIBUTE_HASH
  AND S.SOURCE_UPDATED_AT >= T.SOURCE_UPDATED_AT;

-- Insert new customers and the replacement version for changed customers.
INSERT INTO RETAIL_DW.DW.DIM_CUSTOMER (
  CUSTOMER_ID, CUSTOMER_NAME, EMAIL, PHONE, CITY, STATE, COUNTRY, CUSTOMER_SEGMENT,
  IS_DELETED, ATTRIBUTE_HASH, VALID_FROM, VALID_TO, IS_CURRENT, SOURCE_UPDATED_AT
)
SELECT S.CUSTOMER_ID, S.CUSTOMER_NAME, S.EMAIL, S.PHONE, S.CITY, S.STATE, S.COUNTRY,
       S.CUSTOMER_SEGMENT, S.IS_DELETED, S.ATTRIBUTE_HASH,
       IFF(H.CUSTOMER_ID IS NULL, COALESCE(S.CREATED_AT, S.SOURCE_UPDATED_AT), S.SOURCE_UPDATED_AT),
       TO_TIMESTAMP_TZ('9999-12-31 00:00:00 +00:00'), TRUE, S.SOURCE_UPDATED_AT
FROM RETAIL_DW.STAGING.STG_CUSTOMERS S
LEFT JOIN (SELECT DISTINCT CUSTOMER_ID FROM RETAIL_DW.DW.DIM_CUSTOMER) H
  ON H.CUSTOMER_ID = S.CUSTOMER_ID
WHERE S.BATCH_ID = '{{BATCH_ID}}'
  AND NOT EXISTS (
    SELECT 1 FROM RETAIL_DW.DW.DIM_CUSTOMER T
    WHERE T.CUSTOMER_ID = S.CUSTOMER_ID AND T.IS_CURRENT = TRUE
  );
