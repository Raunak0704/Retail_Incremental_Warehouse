-- Source system tables live in Snowflake. The target warehouse is RETAIL_DW.
-- Snowflake standard-table PK/FK constraints are metadata declarations, not enforced;
-- source data quality and referential integrity are validated by the project scripts.
CREATE DATABASE IF NOT EXISTS RETAIL_SOURCE;
CREATE SCHEMA IF NOT EXISTS RETAIL_SOURCE.RETAIL;

CREATE TABLE IF NOT EXISTS RETAIL_SOURCE.RETAIL.CUSTOMERS (
    CUSTOMER_ID       NUMBER(38,0) NOT NULL,
    CUSTOMER_NAME     VARCHAR(200) NOT NULL,
    EMAIL             VARCHAR(320),
    PHONE             VARCHAR(40),
    CITY              VARCHAR(100),
    STATE             VARCHAR(100),
    COUNTRY           VARCHAR(100) NOT NULL DEFAULT 'India',
    CUSTOMER_SEGMENT  VARCHAR(40) NOT NULL DEFAULT 'STANDARD',
    IS_DELETED        BOOLEAN NOT NULL DEFAULT FALSE,
    CREATED_AT        TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_AT        TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_SOURCE_CUSTOMERS PRIMARY KEY (CUSTOMER_ID)
);

CREATE TABLE IF NOT EXISTS RETAIL_SOURCE.RETAIL.PRODUCTS (
    PRODUCT_ID        NUMBER(38,0) NOT NULL,
    SKU               VARCHAR(80) NOT NULL,
    PRODUCT_NAME      VARCHAR(200) NOT NULL,
    CATEGORY          VARCHAR(100) NOT NULL,
    BRAND             VARCHAR(100),
    UNIT_PRICE        NUMBER(14,2) NOT NULL,
    IS_ACTIVE         BOOLEAN NOT NULL DEFAULT TRUE,
    IS_DELETED        BOOLEAN NOT NULL DEFAULT FALSE,
    CREATED_AT        TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_AT        TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_SOURCE_PRODUCTS PRIMARY KEY (PRODUCT_ID),
    CONSTRAINT UQ_SOURCE_PRODUCTS_SKU UNIQUE (SKU)
);

CREATE TABLE IF NOT EXISTS RETAIL_SOURCE.RETAIL.ORDERS (
    ORDER_ID          NUMBER(38,0) NOT NULL,
    CUSTOMER_ID       NUMBER(38,0) NOT NULL,
    ORDER_TS          TIMESTAMP_TZ NOT NULL,
    ORDER_STATUS      VARCHAR(30) NOT NULL,
    PAYMENT_STATUS    VARCHAR(30) NOT NULL,
    TOTAL_AMOUNT      NUMBER(16,2) NOT NULL,
    CURRENCY          VARCHAR(3) NOT NULL DEFAULT 'INR',
    IS_DELETED        BOOLEAN NOT NULL DEFAULT FALSE,
    CREATED_AT        TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_AT        TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_SOURCE_ORDERS PRIMARY KEY (ORDER_ID),
    CONSTRAINT FK_SOURCE_ORDERS_CUSTOMER FOREIGN KEY (CUSTOMER_ID)
      REFERENCES RETAIL_SOURCE.RETAIL.CUSTOMERS (CUSTOMER_ID)
);

CREATE TABLE IF NOT EXISTS RETAIL_SOURCE.RETAIL.ORDER_ITEMS (
    ORDER_ITEM_ID     NUMBER(38,0) NOT NULL,
    ORDER_ID          NUMBER(38,0) NOT NULL,
    PRODUCT_ID        NUMBER(38,0) NOT NULL,
    QUANTITY          NUMBER(10,0) NOT NULL,
    UNIT_PRICE        NUMBER(14,2) NOT NULL,
    DISCOUNT_AMOUNT   NUMBER(14,2) NOT NULL DEFAULT 0,
    LINE_AMOUNT       NUMBER(16,2) NOT NULL,
    ITEM_STATUS       VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',
    IS_DELETED        BOOLEAN NOT NULL DEFAULT FALSE,
    CREATED_AT        TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_AT        TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_SOURCE_ORDER_ITEMS PRIMARY KEY (ORDER_ITEM_ID),
    CONSTRAINT FK_SOURCE_ITEMS_ORDER FOREIGN KEY (ORDER_ID)
      REFERENCES RETAIL_SOURCE.RETAIL.ORDERS (ORDER_ID),
    CONSTRAINT FK_SOURCE_ITEMS_PRODUCT FOREIGN KEY (PRODUCT_ID)
      REFERENCES RETAIL_SOURCE.RETAIL.PRODUCTS (PRODUCT_ID)
);

-- No row-level triggers exist in Snowflake. Every source writer must set UPDATED_AT
-- explicitly on UPDATE. The included mutation utility does this with CURRENT_TIMESTAMP().
